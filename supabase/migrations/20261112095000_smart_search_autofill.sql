-- Ride24 Smart Search: deterministic safe EN->PL enrichment (no booking/API mutation).
-- Reads active partner locations, inserts into dictionary only when translation is verified.
-- Existing dictionary rows are never updated/deleted; unknown/ambiguous phrases remain unassigned.
CREATE SCHEMA IF NOT EXISTS ride24_smart_internal;
REVOKE ALL ON SCHEMA ride24_smart_internal FROM public, anon, authenticated;
GRANT USAGE ON SCHEMA ride24_smart_internal TO service_role;

CREATE TABLE IF NOT EXISTS ride24_smart_internal.settings (
 singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
 enabled boolean NOT NULL DEFAULT false,
 updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO ride24_smart_internal.settings(singleton,enabled)
 VALUES(true,true) ON CONFLICT(singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS ride24_smart_internal.rules (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category text NOT NULL CHECK(category IN ('country','region','city','location')),
 name_en text NOT NULL,
 parent_country_en text NOT NULL DEFAULT '',
 parent_region_en text NOT NULL DEFAULT '',
 name_pl text NOT NULL,
 verified boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(category,name_en,parent_country_en,parent_region_en)
);
CREATE TABLE IF NOT EXISTS ride24_smart_internal.runs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(),
 dry_run boolean NOT NULL,
 enabled boolean NOT NULL,
 inspected int NOT NULL DEFAULT 0,
 candidates int NOT NULL DEFAULT 0,
 inserted int NOT NULL DEFAULT 0,
 sample jsonb NOT NULL DEFAULT '[]'::jsonb
);
CREATE TABLE IF NOT EXISTS ride24_smart_internal.changes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id bigint NOT NULL REFERENCES ride24_smart_internal.runs(id),
 dictionary_id uuid NOT NULL,
 category text NOT NULL,
 name_en text NOT NULL,
 name_pl text NOT NULL,
 parent_country_en text,
 parent_region_en text,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(dictionary_id)
);
CREATE TABLE IF NOT EXISTS ride24_smart_internal.dictionary_before_autofill
AS SELECT id,category,name_en,name_pl,keywords,slug,parent_country_en,parent_region_en
  FROM public.locations_dictionary;

ALTER TABLE ride24_smart_internal.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE ride24_smart_internal.rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE ride24_smart_internal.runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE ride24_smart_internal.changes ENABLE ROW LEVEL SECURITY;
ALTER TABLE ride24_smart_internal.dictionary_before_autofill ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA ride24_smart_internal FROM public,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA ride24_smart_internal TO service_role;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA ride24_smart_internal TO service_role;

