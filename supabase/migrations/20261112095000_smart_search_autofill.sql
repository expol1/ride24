CREATE OR REPLACE FUNCTION ride24_smart_internal.process(p_dry_run boolean DEFAULT true)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
declare
 rec record;
 v_enabled boolean;
 v_rid bigint;
 v_inspected int := 0;
 v_candidates int := 0;
 v_inserted int := 0;
 v_pl text;
 v_country text;
 v_region text;
 v_city text;
 v_suffix text;
 v_match text[];
 v_unique int;
 v_new_id uuid;
 v_example jsonb := '[]'::jsonb;
 v_slug text;
begin
  select enabled into v_enabled from ride24_smart_internal.settings where singleton;
  if v_enabled is distinct from true and p_dry_run is false then
    return jsonb_build_object('enabled',false,'dry_run',p_dry_run,'message','Autofill disabled');
  end if;
  insert into ride24_smart_internal.runs(dry_run,enabled) values(p_dry_run,coalesce(v_enabled,false)) returning id into v_rid;

  for rec in
    select distinct v.category, btrim(v.name_en) name_en,
      case when v.category='country' then '' else coalesce(btrim(p.country),'') end country,
      case when v.category in ('city','location') then coalesce(btrim(p.region),'') else '' end region
    from public.partner_locations p
    cross join lateral (values
      ('country'::text,p.country), ('region',p.region), ('city',p.city), ('location',p.location_name)
    ) v(category,name_en)
    where p.active is true and length(btrim(coalesce(v.name_en,''))) between 2 and 200
    order by 1,2,3,4
    limit 2000
  loop
    v_inspected := v_inspected + 1;
    if lower(rec.name_en) like 'test%' then continue; end if;
    if exists (
      select 1 from public.locations_dictionary d
      where d.category = rec.category
        and lower(btrim(d.name_en))=lower(rec.name_en)
        and (rec.country='' or coalesce(btrim(d.parent_country_en),'')='' or lower(btrim(d.parent_country_en))=lower(rec.country))
        and (rec.region='' or coalesce(btrim(d.parent_region_en),'')='' or lower(btrim(d.parent_region_en))=lower(rec.region))
    ) then continue; end if;

    v_pl := null;
    select count(distinct lower(btrim(x.name_pl))),min(x.name_pl) into v_unique,v_pl
      from ride24_smart_internal.rules x
      where x.verified and x.category=rec.category
        and lower(btrim(x.name_en))=lower(rec.name_en)
        and (x.parent_country_en='' or lower(btrim(x.parent_country_en))=lower(rec.country))
        and (x.parent_region_en='' or lower(btrim(x.parent_region_en))=lower(rec.region));
    if v_unique <> 1 then v_pl:=null; end if;

    -- A safe productive rule: canonical city + a well-known pickup suffix.
    -- It NEVER guesses a city or creates an actual pickup point.
    if v_pl is null and rec.category='location' then
      v_match := regexp_match(rec.name_en, '^(.*?)\s+(airport|downtown|city|port|train station)$', 'i');
      if v_match is not null then
        v_city:=btrim(v_match[1]);
        v_suffix:=lower(v_match[2]);
        select count(distinct lower(btrim(t.name_pl))),min(t.name_pl) into v_unique,v_pl
        from (
          select name_pl from public.locations_dictionary d
          where d.category='city' and lower(btrim(d.name_en))=lower(v_city)
            and btrim(d.name_pl)<>'' and
            (coalesce(btrim(d.parent_country_en),'')='' or lower(btrim(d.parent_country_en))=lower(rec.country))
          union all
          select name_pl from ride24_smart_internal.rules x
          where x.verified and x.category='city' and lower(btrim(x.name_en))=lower(v_city)
            and (x.parent_country_en='' or lower(btrim(x.parent_country_en))=lower(rec.country))
        ) t;
        if v_unique = 1 then
          v_pl := case v_suffix
            when 'airport' then 'Lotnisko '||v_pl
            when 'downtown' then v_pl||' – centrum'
            when 'city' then v_pl||' – centrum'
            when 'port' then 'Port '||v_pl
            when 'train station' then v_pl||' – dworzec kolejowy'
            else null end;
        else v_pl:=null; end if;
      end if;
    end if;
    if v_pl is null or btrim(v_pl)='' or length(v_pl)>250 then continue; end if;
    v_candidates:=v_candidates+1;
    if jsonb_array_length(v_example)<10 then
      v_example:=v_example||jsonb_build_array(jsonb_build_object(
        'category',rec.category,'original',rec.name_en,'polish',v_pl,'country',rec.country));
    end if;
    if p_dry_run then continue; end if;
    v_slug:='smart-auto-'||md5(rec.category||'|'||lower(rec.name_en)||'|'||lower(rec.country)||'|'||lower(rec.region));
    v_new_id:=null;
    insert into public.locations_dictionary
      (id,category,name_en,name_pl,keywords,slug,parent_country_en,parent_region_en)
    select gen_random_uuid(),rec.category,rec.name_en,v_pl,'',v_slug,
        nullif(rec.country,''), nullif(rec.region,'')
    where not exists (
      select 1 from public.locations_dictionary d
      where d.category=rec.category and lower(btrim(d.name_en))=lower(rec.name_en)
        and (rec.country='' or coalesce(btrim(d.parent_country_en),'')='' or lower(btrim(d.parent_country_en))=lower(rec.country))
        and (rec.region='' or coalesce(btrim(d.parent_region_en),'')='' or lower(btrim(d.parent_region_en))=lower(rec.region))
    )
    on conflict (slug) do nothing
    returning id into v_new_id;
    if v_new_id is not null then
      v_inserted := v_inserted+1;
      insert into ride24_smart_internal.changes
        (run_id,dictionary_id,category,name_en,name_pl,parent_country_en,parent_region_en)
      values(v_rid,v_new_id,rec.category,rec.name_en,v_pl,nullif(rec.country,''),nullif(rec.region,''));
    end if;
  end loop;
  update ride24_smart_internal.runs set
    inspected=v_inspected,candidates=v_candidates,inserted=v_inserted,sample=v_example where id=v_rid;
  return jsonb_build_object('enabled',coalesce(v_enabled,false),'dry_run',p_dry_run,
    'inspected',v_inspected,'candidates',v_candidates,'inserted',v_inserted,'run_id',v_rid,'sample',v_example);
end;
$function$

REVOKE ALL ON FUNCTION ride24_smart_internal.process(boolean) FROM public,anon,authenticated;
GRANT EXECUTE ON FUNCTION ride24_smart_internal.process(boolean) TO service_role;

CREATE OR REPLACE FUNCTION public.smart_search_automation_status()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
declare v jsonb;
begin
  if not public.is_admin() then
    raise exception using errcode='42501',message='ADMIN_ONLY';
  end if;
  select jsonb_build_object(
    'enabled',(select enabled from ride24_smart_internal.settings where singleton),
    'latest',(select jsonb_build_object('date',created_at,'dry_run',dry_run,'inspected',inspected,'candidates',candidates,'inserted',inserted)
               from ride24_smart_internal.runs order by id desc limit 1),
    'total_added',(select count(*) from ride24_smart_internal.changes)
  ) into v;
  return v;
end;
$function$

REVOKE ALL ON FUNCTION public.smart_search_automation_status() FROM public,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.smart_search_automation_status() TO authenticated;

