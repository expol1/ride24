/**
 * Caravel-only post-Stripe orchestration, isolated from AVIA/Renteon.
 *
 * NOT DEPLOYED: requires reviewed Caravel migrations, verified clauses/v1
 * canonical hash, stored pre-Stripe customer consent, valid supplier
 * credentials, 24h certification and explicit production activation.
 *
 * Server input only. Never call from a browser. A signed Stripe webhook
 * must have ALREADY queued the paid booking via caravel-payment-commit.
 * All supplier reads, immutable quote evidence and DB writes require
 * a service-role Supabase client.
 *
 * Outcomes:
 * - confirmed: supplier booking persisted, voucher MAY be generated by the
 *   separately authorized voucher/email worker (not by this module)
 * - manual_review: paid state held and safe evidence written to existing
 *   booking_review_queue; no automatic retry/refund
 * - skipped: another dispatcher won the atomic claim or booking ineligible
 * - hold_unqueued: DB/review failure; do not retry remote booking blindly
 */
import {prepareVerifiedCaravelDispatch}
  from "./caravel-dispatch-gate.ts";
import {claimCaravelPaidDispatch,type CaravelClaimClient}
  from "./caravel-dispatch-claim.ts";
import {submitVerifiedCaravelBooking}
  from "./caravel-provider-bridge.ts";
import {commitVerifiedCaravelSupplierConfirmation,
  type CaravelConfirmationAdmin}
  from "./caravel-confirmation-commit.ts";
import {queueCaravelSupplierManualReview,
  type CaravelReviewAdmin,type CaravelSupplierFailure}
  from "./caravel-manual-review.ts";

type BridgeArgs=Parameters<typeof submitVerifiedCaravelBooking>[0];
type Admin=CaravelClaimClient&CaravelConfirmationAdmin&CaravelReviewAdmin;
type Args=Omit<BridgeArgs,"persistedPaidBooking">&{admin:Admin};
export type CaravelOperationalResult=
 |{ok:true;status:"confirmed";bookingId:string;
   providerReference:string;mayGenerateVoucher:true;mayNotifyCustomer:true}
 |{ok:false;status:"manual_review"|"hold_unqueued"|"skipped";
   reason:string;bookingId:string;providerReference:string|null;
   mayGenerateVoucher:false;mayNotifyCustomer:false;
   mayAutomaticallyRetry:false;mayAutomaticallyRefund:false};
const UUID=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const CODE=/^[A-Z][A-Z0-9_]{2,95}$/;
const safeReason=(x:unknown):string=>
  typeof x==="string"&&CODE.test(x)?
    (x.startsWith("CARAVEL_")?x:"CARAVEL_"+x).slice(0,100):
    "CARAVEL_UNCLASSIFIED_PROVIDER_FAILURE";

const block=(bookingId:string,reason:string,
  status:"manual_review"|"hold_unqueued"|"skipped",
  ref:string|null):CaravelOperationalResult=>({
  ok:false,status,reason,bookingId,providerReference:ref,
  mayGenerateVoucher:false,mayNotifyCustomer:false,
  mayAutomaticallyRetry:false,mayAutomaticallyRefund:false,
});
/** The only API that may turn a Caravel supplier failure into an admin case.
 * A failed review write does not unlock supplier re-dispatch.
 */
async function hold(args:Args,bookingId:string,
  phase:CaravelSupplierFailure["phase"],reasons:unknown[],
  providerReference:unknown):Promise<CaravelOperationalResult>{
 const codes=reasons.map(safeReason).slice(0,12);
 if(codes.length===0)codes.push("CARAVEL_UNCLASSIFIED_PROVIDER_FAILURE");
 const ref=typeof providerReference==="string"&&UUID.test(providerReference)
   ?providerReference:null;
 const review=await queueCaravelSupplierManualReview({
   admin:args.admin,bookingId,
   outcome:{phase,reasons:codes,externalReference:ref},
 });
 if(review.ok){
   return block(bookingId,codes[0],"manual_review",ref);
 }
 return block(bookingId,"reason" in review?review.reason:
   "CARAVEL_REVIEW_PERSISTENCE_FAILED","hold_unqueued",ref);
}
/**
 * Certified operator worker entrypoint, never the shared supplier-first
 * dispatcher. A duplicate invocation receives "skipped" and can neither
 * place a second Caravel booking nor move the first worker into review.
 */
export async function processVerifiedCaravelPaidBooking(
  args:Args):Promise<CaravelOperationalResult>{
 const bookingId=String(args?.bookingInput?.ride24_booking_id??"");
 if(!UUID.test(bookingId)||!args?.admin||!args?.bookingInput)
   return block(bookingId,"CARAVEL_ORCHESTRATION_INPUT_INVALID",
     "hold_unqueued",null);
 if(args.enableSupplierWrite!==true||
    args.client?.environment!=="production"||
    args.partnerApiEnabled!==true||
    args.currentExternalReference!==null||
    !Number.isSafeInteger(args.nowEpochMs))
   return block(bookingId,"CARAVEL_LIVE_DISPATCH_NOT_AUTHORIZED",
     "hold_unqueued",null);

 // Pure preflight BEFORE touching supplier or claiming a durable DB row.
 const preflight=prepareVerifiedCaravelDispatch({
   bookingInput:args.bookingInput,nowEpochMs:args.nowEpochMs,
   productionGate:args.productionGate,
   reviewedTerms:args.reviewedTerms,
   currentTermsMetadataList:args.currentTermsMetadataList,
   persistedBookingTerms:args.persistedBookingTerms,
   persistedCoverageConsent:args.persistedCoverageConsent,
 });
 if("reasons" in preflight)
   return hold(args,bookingId,"preflight",preflight.reasons,null);

 const claim=await claimCaravelPaidDispatch({
   admin:args.admin,bookingId,
   nowIso:new Date(args.nowEpochMs).toISOString(),
   partnerApiEnabled:args.partnerApiEnabled,
   providerQuote:args.bookingInput.provider_quote_data,
 });
 if("reason" in claim){
   if(claim.reason==="CARAVEL_CLAIM_ALREADY_TAKEN_OR_INELIGIBLE")
     return block(bookingId,claim.reason,"skipped",null);
   // A failed post-UPDATE verification may still have claimed a row.
   // Persist review evidence where possible rather than blind re-dispatch.
   if(claim.reason==="CARAVEL_CLAIM_DB_REQUEST_FAILED")
     return block(bookingId,claim.reason,"hold_unqueued",null);
   return hold(args,bookingId,"preflight",[claim.reason],null);
 }
 const provider=await submitVerifiedCaravelBooking({
   ...args,persistedPaidBooking:claim.persistedBooking,
 });
 if("reasons" in provider){
   return hold(args,bookingId,provider.phase,
     provider.reasons,provider.externalReference);
 }
 const result=await commitVerifiedCaravelSupplierConfirmation({
   admin:args.admin,bookingId,
   paidClaim:claim.persistedBooking,
   verifiedProviderResult:provider.result,
   nowIso:new Date(args.nowEpochMs).toISOString(),
 });
 if("reason" in result){
   return hold(args,bookingId,"confirmation",
     [result.reason],result.providerReference);
 }
 return {ok:true,status:"confirmed",bookingId,
   providerReference:result.providerReference,
   mayGenerateVoucher:true,mayNotifyCustomer:true};
}
